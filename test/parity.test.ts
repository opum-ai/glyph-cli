import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { mkdirSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { produceCodeMap } from "../src/codemap.ts";
import { OPUM_CLI_PIN } from "../src/codemap-text.ts";
import { FIXTURES, makeFixtureRepo } from "./parity/fixtures.ts";
import { type GoldenFile, GOLDENS_PATH, OPUM_CLI_SHA } from "./parity/generate-goldens.ts";

/**
 * Parity with opum-cli's deterministic producer (GCLI-41, DEC-216 (a7)).
 *
 * `goldens.json` holds the producer's own output for each fixture, generated by
 * `bun run test/parity/generate-goldens.ts` from opum-cli at the pinned SHA. This
 * test runs the same fixtures through glyph's port and compares BYTES. It never
 * touches opum-cli: glyph's CI has no cross-repository dependency.
 */

const goldens = JSON.parse(readFileSync(GOLDENS_PATH, "utf8")) as GoldenFile;

function builtFixture(name: string): { root: string; taskText: string; sourceRef: string } {
	const fixture = FIXTURES.find((candidate) => candidate.name === name);
	if (fixture === undefined) throw new Error(`no fixture ${name}`);
	const root = join(mkdtempSync(join(tmpdir(), "glyph-parity-")), name);
	mkdirSync(root, { recursive: true });
	fixture.build(makeFixtureRepo(root));
	return { root, taskText: fixture.taskText, sourceRef: fixture.sourceRef };
}

describe("the golden pin", () => {
	test("a golden's header pin equals the generator's constant, which equals the port's pin", () => {
		expect(goldens.pin).toBe(OPUM_CLI_SHA);
		expect(OPUM_CLI_SHA).toBe(OPUM_CLI_PIN);
		expect(goldens.pin).toMatch(/^[0-9a-f]{40}$/);
	});

	test("the goldens cover exactly the fixtures, with their inputs", () => {
		expect(Object.keys(goldens.fixtures).sort()).toEqual(FIXTURES.map((fixture) => fixture.name).sort());
		for (const fixture of FIXTURES) {
			expect(goldens.fixtures[fixture.name]?.taskText).toBe(fixture.taskText);
			expect(goldens.fixtures[fixture.name]?.sourceRef).toBe(fixture.sourceRef);
		}
	});
});

describe("byte parity with the deterministic producer", () => {
	for (const fixture of FIXTURES) {
		test(`${fixture.name}: glyph's output is byte-identical to the producer's golden`, () => {
			const { root, taskText, sourceRef } = builtFixture(fixture.name);
			const output = produceCodeMap({ repositoryPath: root, sourceRef, taskText });
			expect(JSON.stringify(output, null, 2)).toBe(JSON.stringify(goldens.fixtures[fixture.name]?.output, null, 2));
		});
	}

	test("the fixtures exercise what they claim: caps, a rename as delete plus add, ranges, non-code paths", () => {
		const output = (name: string) =>
			goldens.fixtures[name]?.output as {
				pointers: { path: string; lineRanges: string[]; reason: string }[];
				omissions: { source: string; reason: string }[];
			};
		const fileCap = output("file-cap");
		expect(fileCap.pointers).toHaveLength(20);
		expect(fileCap.omissions.some((row) => row.source === "code-map#file-cap")).toBe(true);
		expect(fileCap.omissions.some((row) => row.source === "code-map#read-bounds")).toBe(true);

		const tokenCap = output("token-cap");
		expect(tokenCap.pointers.length).toBeLessThan(20);
		expect(tokenCap.omissions.some((row) => row.reason.startsWith("over the code-map token cap"))).toBe(true);

		// --no-renames: the renamed file is an add (new name, branch-changed) and the old
		// path is still pointed to at the source ref by its identifier.
		const rename = output("rename");
		expect(rename.pointers.map((pointer) => pointer.path)).toContain("src/new-name.ts");
		expect(rename.pointers.find((pointer) => pointer.path === "src/new-name.ts")?.reason).toContain(
			"changed on this branch",
		);

		const ranges = output("ranges");
		expect(ranges.pointers.some((pointer) => pointer.lineRanges.some((range) => range.startsWith("+")))).toBe(true);

		const special = output("special-paths");
		expect(
			special.pointers.some((pointer) => pointer.path.startsWith(".quest/") || pointer.path.startsWith(".lore/")),
		).toBe(false);
	});

	test("the same repository state and task text yield byte-identical output twice", () => {
		const { root, taskText, sourceRef } = builtFixture("clean");
		const first = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText }));
		const second = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText }));
		expect(second).toBe(first);
	});
});
