import { beforeAll, describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { produceCodeMap } from "../src/codemap.ts";
import { OPUM_CLI_PIN } from "../src/codemap-text.ts";
import { FIXTURES, makeFixtureRepo } from "./parity/fixtures.ts";
import { type GoldenFile, GOLDENS_PATH, OPUM_CLI_SHA } from "./parity/generate-goldens.ts";

/**
 * Parity with opum-cli's deterministic producer (GCLI-41, DEC-216 (a7)).
 *
 * `goldens.json` holds the producer's own output for each fixture, generated by
 * `bun run test/parity/generate-goldens.ts` from opum-cli at the pinned SHA. This
 * test runs the same fixtures through glyph's port and compares BYTES. It never
 * touches opum-cli: glyph's CI has no cross-repository dependency.
 */

beforeAll(() => {
	// Tier 3 builds an index cache; keep it out of the user's ~/.cache/glyph.
	process.env.GLYPH_CACHE_DIR = mkdtempSync(join(tmpdir(), "glyph-parity-cache-"));
});

const goldens = JSON.parse(readFileSync(GOLDENS_PATH, "utf8")) as GoldenFile;

function builtFixture(name: string): { root: string; taskText: string; sourceRef: string } {
	const fixture = FIXTURES.find((candidate) => candidate.name === name);
	if (fixture === undefined) throw new Error(`no fixture ${name}`);
	const root = join(mkdtempSync(join(tmpdir(), "glyph-parity-")), name);
	mkdirSync(root, { recursive: true });
	fixture.build(makeFixtureRepo(root));
	return { root, taskText: fixture.taskText, sourceRef: fixture.sourceRef };
}

describe("the golden pin", () => {
	test("a golden's header pin equals the generator's constant, which equals the port's pin", () => {
		expect(goldens.pin).toBe(OPUM_CLI_SHA);
		expect(OPUM_CLI_SHA).toBe(OPUM_CLI_PIN);
		expect(goldens.pin).toMatch(/^[0-9a-f]{40}$/);
	});

	test("the goldens cover exactly the fixtures, with their inputs", () => {
		expect(Object.keys(goldens.fixtures).sort()).toEqual(FIXTURES.map((fixture) => fixture.name).sort());
		for (const fixture of FIXTURES) {
			expect(goldens.fixtures[fixture.name]?.taskText).toBe(fixture.taskText);
			expect(goldens.fixtures[fixture.name]?.sourceRef).toBe(fixture.sourceRef);
		}
	});
});

describe("byte parity with the deterministic producer", () => {
	for (const fixture of FIXTURES) {
		test(`${fixture.name}: glyph's output is byte-identical to the producer's golden`, () => {
			const { root, taskText, sourceRef } = builtFixture(fixture.name);
			const output = produceCodeMap({ repositoryPath: root, sourceRef, taskText, symbols: false });
			expect(JSON.stringify(output, null, 2)).toBe(JSON.stringify(goldens.fixtures[fixture.name]?.output, null, 2));
		});
	}

	for (const [label, loadIndex] of [
		[
			"a throwing index loader",
			() => {
				throw new Error("index exploded");
			},
		],
		["an absent index", () => null],
	] as const) {
		for (const fixture of FIXTURES) {
			test(`the fallback is a true control: ${label} gives the producer's golden bytes with tier 3 on (${fixture.name})`, () => {
				const { root, taskText, sourceRef } = builtFixture(fixture.name);
				const output = produceCodeMap({ repositoryPath: root, sourceRef, taskText, loadIndex });
				expect(JSON.stringify(output, null, 2)).toBe(JSON.stringify(goldens.fixtures[fixture.name]?.output, null, 2));
			});
		}
	}

	test("the fixtures exercise what they claim: caps, a rename as delete plus add, ranges, non-code paths", () => {
		const output = (name: string) =>
			goldens.fixtures[name]?.output as {
				pointers: { path: string; lineRanges: string[]; reason: string }[];
				omissions: { source: string; reason: string }[];
			};
		const fileCap = output("file-cap");
		expect(fileCap.pointers).toHaveLength(20);
		expect(fileCap.omissions.some((row) => row.source === "code-map#file-cap")).toBe(true);
		expect(fileCap.omissions.some((row) => row.source === "code-map#read-bounds")).toBe(true);

		const tokenCap = output("token-cap");
		expect(tokenCap.pointers.length).toBeLessThan(20);
		expect(tokenCap.omissions.some((row) => row.reason.startsWith("over the code-map token cap"))).toBe(true);

		// --no-renames: the renamed file is an add (new name, branch-changed) and the old
		// path is still pointed to at the source ref by its identifier.
		const rename = output("rename");
		expect(rename.pointers.map((pointer) => pointer.path)).toContain("src/new-name.ts");
		expect(rename.pointers.find((pointer) => pointer.path === "src/new-name.ts")?.reason).toContain(
			"changed on this branch",
		);

		const ranges = output("ranges");
		expect(ranges.pointers.some((pointer) => pointer.lineRanges.some((range) => range.startsWith("+")))).toBe(true);

		const special = output("special-paths");
		expect(
			special.pointers.some((pointer) => pointer.path.startsWith(".quest/") || pointer.path.startsWith(".lore/")),
		).toBe(false);
	});

	test("the golden fixtures name no symbol their index declares only by name, but tier 3 still adds files to `clean`", () => {
		// Tier 3 is the one tier the producer lacks, so the parity runs above switch it off:
		// with it on, `clean` (a task naming `buildReport`, a declared function) gains
		// symbol pointers. That is the difference, not a parity break.
		const { root, taskText, sourceRef } = builtFixture("clean");
		const off = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText, symbols: false }));
		const on = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText }));
		expect(on).not.toBe(off);
	});

	// One test per fixture: the whole loop in one test ran past bun's 5 s default under load (GCLI-58).
	for (const fixture of FIXTURES)
		test(`output does not depend on the caller's git config: a hostile global config gives the same bytes (${fixture.name})`, () => {
			// quotepath=false would unquote the non-ASCII grep path, color.ui and color.grep
			// would put ANSI codes into the paths, and the diff.* and grep.* settings would
			// move hunk boundaries and line numbers if the reads did not pin them.
			const config = join(mkdtempSync(join(tmpdir(), "glyph-hostile-")), "gitconfig");
			writeFileSync(
				config,
				[
					"[core]\n\tquotepath = false",
					"[color]\n\tui = always\n\tgrep = always",
					"[diff]\n\talgorithm = patience\n\tindentHeuristic = true\n\tinterHunkContext = 5",
					"[grep]\n\tlineNumber = false\n\tfullName = true",
					"",
				].join("\n"),
			);
			const saved = {
				global: process.env.GIT_CONFIG_GLOBAL,
				system: process.env.GIT_CONFIG_NOSYSTEM,
				cache: process.env.GLYPH_CACHE_DIR,
			};
			const withPlainConfig = (run: () => void): void => {
				process.env.GIT_CONFIG_GLOBAL = "/dev/null";
				try {
					run();
				} finally {
					process.env.GIT_CONFIG_GLOBAL = config;
				}
			};
			try {
				// Positive control: the hostile environment is in force, so the equal bytes below
				// were produced under it and not under git's defaults.
				process.env.GIT_CONFIG_GLOBAL = config;
				process.env.GIT_CONFIG_NOSYSTEM = "1";
				const quotepath = spawnSync("git", ["config", "core.quotepath"], { encoding: "utf8", env: { ...process.env } });
				expect(quotepath.stdout.trim()).toBe("false");
				const { root, taskText, sourceRef } = builtFixture(fixture.name);
				const output = produceCodeMap({ repositoryPath: root, sourceRef, taskText, symbols: false });
				expect(JSON.stringify(output, null, 2)).toBe(JSON.stringify(goldens.fixtures[fixture.name]?.output, null, 2));
				// Tier 3 on: the same bytes under the hostile config as under the plain one.
				// Each run builds its own index (a cache dir per run), so the build itself is compared.
				const freshCache = (): void => {
					process.env.GLYPH_CACHE_DIR = mkdtempSync(join(tmpdir(), "glyph-hostile-cache-"));
				};
				freshCache();
				const hostileOn = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText }));
				withPlainConfig(() => {
					freshCache();
					expect(hostileOn).toBe(JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText })));
				});
			} finally {
				for (const [name, value] of [
					["GIT_CONFIG_GLOBAL", saved.global],
					["GIT_CONFIG_NOSYSTEM", saved.system],
					["GLYPH_CACHE_DIR", saved.cache],
				] as const) {
					if (value === undefined) delete process.env[name];
					else process.env[name] = value;
				}
			}
		});

	test("the same repository state and task text yield byte-identical output twice", () => {
		const { root, taskText, sourceRef } = builtFixture("clean");
		const first = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText, symbols: false }));
		const second = JSON.stringify(produceCodeMap({ repositoryPath: root, sourceRef, taskText, symbols: false }));
		expect(second).toBe(first);
	});
});
